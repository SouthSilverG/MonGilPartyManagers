function guidePickerItems(items, entries) {
  const normalize=s=>String(s||'').replace(/\s/g,'');
  return items.map((item,index)=>{
    const entry=entries.find(e=>normalize(e.name)===normalize(item.name));
    if(!entry)return {...item,_guideRank:100000+index};
    return {...item,recommended:true,recommendationLabel:entry.alternative?'대체':'추천',recommendationAlternative:!!entry.alternative,recommendationNote:entry.note||'',recommendationTitle:'캐릭터 가이드 기준 · '+(entry.note||'추천'),_guideRank:(entry.alternative?1000:0)+entries.indexOf(entry)};
  }).sort((a,b)=>a._guideRank-b._guideRank).map(({_guideRank,...item})=>item);
}
function equipmentPickerItems(characterId,part) {
  const guide=CHARACTER_GEAR_GUIDES[characterId];
  return guidePickerItems(EQUIPMENT[part]||[],(guide?.equipment||[]).filter(e=>!e.parts||e.parts.includes(part)).map(e=>({...e,note:e.pieces+'세트'})));
}
function monsterPickerItems(characterId,items,kind) {
  const guide=CHARACTER_GEAR_GUIDES[characterId];
  const entries=!guide?[]:kind==='legend'?[{name:guide.legend,note:''}]:[
    ...guide.link.map(e=>({...e,note:'링크 체인'})),
    ...guide.sub.map(e=>({...e,note:'서브'}))
  ];
  return guidePickerItems(items,entries);
}
