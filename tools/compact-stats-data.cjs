const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');

// Keep the source dump outside the published site. Rebuild after game-data updates.
function compact(data) {
  const sources = ['Statcal/stats-engine.js', 'Statcal/stats-editor.js',
    ...fs.readdirSync(path.join(root, 'tests')).filter(n => /^stats.*\.cjs$/.test(n)).map(n => 'tests/' + n)];
  const source = sources.map(n => fs.readFileSync(path.join(root, n), 'utf8')).join('\n');
  if (!source.includes('s.level=60;s.levelGrade=4;s.artifactLevel=60;s.artifactGrade=4')) {
    throw new Error('Level policy changed: review status-row filtering before rebuilding.');
  }
  const tables = new Set([...source.matchAll(/\bT\.([A-Z][A-Z_0-9]*)|(?:rows|by)\('([A-Z][A-Z_0-9]*)'/g)].map(m => m[1] || m[2]));
  const fields = new Set(source.match(/\b[A-Z][A-Z_0-9]+\b/g));
  // Dynamically composed field names in the calculation engine.
  for (let i = 1; i <= 6; i++) { fields.add('PARAM_' + i); fields.add('PARAM' + i); }
  for (const key of ['STATUS_TYPE_A', 'STATUS_TYPE_B', 'STATUS_TYPE_C', 'FUSION_VALUE_3', 'FUSION_VALUE_5']) fields.add(key);
  const result = { ...data, tables: {} };
  for (const [name, rows] of Object.entries(data.tables)) {
    if (!tables.has(name)) continue;
    result.tables[name] = Object.fromEntries(Object.entries(rows)
      .filter(([, row]) => !['CHARACTER_STATUS', 'CUBE_STATUS', 'CARD_STATUS'].includes(name) || row.LEVEL === 60)
      .map(([id, row]) => [id, Object.fromEntries(Object.entries(row).filter(([field]) => fields.has(field)))]));
  }
  return result;
}
function readData(filename) {
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(filename, 'utf8'), context, { timeout: 10000 });
  return context.window.STAT_DATA;
}
if (require.main === module) {
  const input = process.argv[2];
  if (!input) throw new Error('Usage: node tools/compact-stats-data.cjs <trusted-full-stats-data.js> [output.js]');
  const output = process.argv[3] || path.join(root, 'Statcal/stats-data.js');
  if (path.resolve(input) === path.resolve(output)) throw new Error('Keep the full source separate from the compact output.');
  const text = '/* Generated by tools/compact-stats-data.cjs; fixed level 60. */\nwindow.STAT_DATA=' + JSON.stringify(compact(readData(input))) + ';\n';
  fs.writeFileSync(output, text);
  console.log('Compact data:', Buffer.byteLength(text), 'bytes');
}
module.exports = { compact, readData };
